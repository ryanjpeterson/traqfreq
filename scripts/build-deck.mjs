// Builds docs/deck/index.html: the progress deck "traqfreq: build phases" as one page you can open from the repo.
// Source: docs/deck/deck.json (order), deck.css (shared look) and slides/<id>.html, copied from the Slides artifact
// (https://claude.ai/artifact/4xm8KY4kxsi36oa9gEToMe) at the end of each session. No dependencies.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'docs', 'deck');
const deck = JSON.parse(readFileSync(join(dir, 'deck.json'), 'utf8'));
const css = readFileSync(join(dir, 'deck.css'), 'utf8');
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const slides = deck.order.map((id) => {
  if (!/^[A-Za-z0-9_-]{1,64}$/.test(id)) throw new Error(`bad slide id ${id}`);
  const html = readFileSync(join(dir, 'slides', `${id}.html`), 'utf8').trim();
  const notes = (html.match(/<aside>([\s\S]*?)<\/aside>/) || [, ''])[1].trim();
  return `<div class="frame">${html}</div>\n${notes ? `<p class="notes">${esc(notes)}</p>` : ''}`;
});
const fonts = Object.values(deck.faces || {}).map((f) => f.href).filter(Boolean)
  .map((h) => `<link rel="stylesheet" href="${h}">`).join('\n');

const page = `<!doctype html>
<!-- Generated by scripts/build-deck.mjs from docs/deck; do not edit. -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(deck.title)}</title>
${fonts}
<style>
${css}
body { margin: 0; padding: 16px; background: #2a2a2a; counter-reset: page; font-family: 'Fira Sans', Arial, sans-serif; }
.frame { width: 1920px; height: 1080px; zoom: var(--z, 0.5); margin: 0 auto 8px; box-shadow: 0 2px 12px #0006; }
.frame > section { position: relative; width: 1920px; height: 1080px; box-sizing: border-box; overflow: hidden; }
.frame > section > aside { display: none; }
.frame .tbl { border-collapse: collapse; }
.frame .tbl th, .frame .tbl td { padding: 10px 14px; text-align: left; vertical-align: top; border-bottom: 1px solid #ccc; }
.notes { max-width: 960px; margin: 0 auto 40px; color: #ddd; font-size: 14px; line-height: 1.5; }
</style>
<script>
const fit = () => document.documentElement.style.setProperty('--z', Math.min(1, (innerWidth - 32) / 1920));
addEventListener('resize', fit); fit();
</script>
</head><body>
${slides.join('\n')}
</body></html>
`;
writeFileSync(join(dir, 'index.html'), page);
console.log(`docs/deck/index.html: ${slides.length} slides`);
